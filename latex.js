export function buildLatex(md) {
  const lines = String(md || '').replace(/\r/g, '').split('\n')
  const out = []
  let inList = false, headerLines = 0, phase = 'pre' // pre -> header (contact lines under the name) -> body
  const closeList = () => { if (inList) { out.push('\\end{itemize}'); inList = false } }
  for (const raw of lines) {
    const line = raw.trimEnd()
    const t = line.trim()
    let m
    if (!t || /^([-*_])\1{2,}$/.test(t)) {
      closeList()
      if (phase === 'header' && headerLines) { out.push('\\end{center}'); phase = 'body' }
      else if (phase === 'header') continue
      else if (out.length && out[out.length - 1] !== '') out.push('')
      continue
    }
    if ((m = t.match(/^#\s+(.*)/)) && phase === 'pre') {
      out.push('\\begin{center}', `{\\fontsize{22}{26}\\selectfont\\bfseries\\color{accent} ${inline(m[1])}}\\\\[4pt]`)
      phase = 'header'
      continue
    }
    if (phase === 'header' && !/^#/.test(t)) { out.push(`{\\small ${inline(t)}}\\\\`); headerLines++; continue }
    if (phase === 'header') { out.push('\\end{center}'); phase = 'body' }
    phase = phase === 'pre' ? 'body' : phase
    if ((m = t.match(/^#{1,2}\s+(.*)/))) { closeList(); out.push(`\\section*{${inline(m[1])}}`); continue }
    if ((m = t.match(/^#{3,}\s+(.*)/))) { closeList(); out.push(`\\subsection*{${inline(m[1])}}`); continue }
    if ((m = t.match(/^[-*•]\s+(.*)/))) {
      if (!inList) { out.push('\\begin{itemize}'); inList = true }
      out.push(`  \\item ${inline(m[1])}`)
      continue
    }
    closeList()
    out.push((entry(t) || inline(t)) + '\\par')
  }
  closeList()
  if (phase === 'header') out.push('\\end{center}')
  const body = out.join('\n').replace(/\n{3,}/g, '\n\n').trim()
  return `${PREAMBLE}\n\\begin{document}\n\n${body}\n\n\\end{document}\n`
}
