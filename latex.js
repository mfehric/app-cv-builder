// Turns the light markdown our tailored CVs use into a clean, self-contained LaTeX
// document that compiles on Overleaf (pdfLaTeX) with only standard packages.
//
// Recognised shapes: "# Name", the contact lines right under it, "## Section",
// "### Subheading", "- bullet", "**Role — Org** — _2023–2026_" entry lines (date
// pushed to the right margin), **bold**, _italic_ / *italic*, [text](url), bare
// URLs and e-mails. "---" rules are dropped (sections already draw their own rule).

const SPECIAL = { '\\': '\\textbackslash{}', '{': '\\{', '}': '\\}', '#': '\\#', '$': '\\$', '%': '\\%', '&': '\\&', '_': '\\_', '^': '\\textasciicircum{}', '~': '\\textasciitilde{}', 'Đ': '\\DJ{}', 'đ': '\\dj{}', '→': '$\\rightarrow$', '·': '\\textperiodcentered{}', '•': '\\textbullet{}', '€': '\\texteuro{}', '…': '\\ldots{}', '–': '--', '—': '---', '‘': '`', '’': "'", '“': '``', '”': "''" }
export const texEscape = (s) => String(s).replace(/[\\{}#$%&_^~Đđ→·•€…–—‘’“”]/g, (c) => SPECIAL[c])
const urlEscape = (u) => String(u).replace(/[\\#%{}]/g, (c) => '\\' + c)

const RE_LINK = /\[([^\]]+)\]\(([^)\s]+)\)/
const RE_URL = /\b(https?:\/\/[^\s)]+[^\s).,;:!?])/
const RE_MAIL = /\b([\w.+-]+@[\w-]+(?:\.[\w-]+)+)\b/
const RE_BOLD = /\*\*(.+?)\*\*|__(.+?)__/
const RE_ITAL = /(^|[\s(])[_*]([^_*]+?)[_*](?=$|[\s).,;:!?])/

// Inline markdown -> LaTeX. Splits on the earliest construct so escaping never touches markup.
export function inline(text) {
  const s = String(text || '').replace(/`/g, '')
  const hits = [
    [RE_LINK, (m) => `\\href{${urlEscape(m[2])}}{${inline(m[1])}}`],
    [RE_URL, (m) => `\\href{${urlEscape(m[1])}}{${texEscape(m[1].replace(/^https?:\/\/(www\.)?/, ''))}}`],
    [RE_MAIL, (m) => `\\href{mailto:${m[1]}}{${texEscape(m[1])}}`],
    [RE_BOLD, (m) => `\\textbf{${inline(m[1] ?? m[2])}}`],
    [RE_ITAL, (m) => `${texEscape(m[1])}\\textit{${inline(m[2])}}`],
  ].map(([re, fn]) => { const m = s.match(re); return m ? { m, fn } : null }).filter(Boolean)
  if (!hits.length) return texEscape(s).replace(/"(.+?)"/g, '``$1\'\'')
  const { m, fn } = hits.sort((a, b) => a.m.index - b.m.index)[0]
  return inline(s.slice(0, m.index)) + fn(m) + inline(s.slice(m.index + m[0].length))
}

// "**Role — Org** — _2023–2026_" (or "**Role** | 2023") -> left part + right-aligned date.
function entry(line) {
  const m = line.match(/^(\*\*.+?\*\*.*?)\s+(?:—|–|-|\|)\s+[_*]?([^_*]{2,40}?)[_*]?\s*$/)
  if (!m || !/\d|present|sada|danas|current/i.test(m[2])) return null
  return `${inline(m[1])}\\hfill{\\small\\textit{${inline(m[2])}}}`
}

